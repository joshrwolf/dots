//! Deterministic skill artifacts from the same tree used by the parser.
use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context as _, Result, ensure};

use clap::{Command, CommandFactory as _};

use crate::command::Cli;

const GUIDANCE: &str = "Use `dots` for supported workflows before assembling equivalent shell/API calls. Native tools remain available for unsupported operations or useful follow-up.\n\nStart with `dots --help` to discover the installed command groups, then use the relevant command's `--help`. For detailed syntax, read [the generated command reference](references/commands.md). Help is authoritative if this skill and the installed binary differ.\n\nFor agent workflows, request `--json`; generated dots follow-up commands preserve JSON mode.\n\nUse the task's explicit target or working directory; do not silently substitute another checkout or workspace. Follow the references and next commands returned by the tool. Treat partial or unavailable evidence as such. Tool availability does not authorize mutations beyond the user's request.\n\nIn Herdr, register every PR you create or start working on with `dots herdr prs register <full-pr-url> --workspace <verified-id> --json`, including sequential PRs in the same workspace. Every PR command requires an explicit workspace. Verify it against the task and live workspace inventory (`herdr api snapshot`); never copy inherited Herdr IDs, use UI focus, or treat a matching checkout as proof of ownership. Shared daemons can carry another pane's IDs. If the intended workspace is ambiguous, ask before registering. Registration is idempotent and independent of GitHub availability. Keep earlier registrations; unregister only when explicitly correcting an association. The background plugin watches status; registration does not authorize CI fixes, monitoring by the agent, or merging.\n\nFor multi-PR efforts, `dots task` is the shared work list for a project across sessions and worktrees. Plan slices as tasks under a parent, record prerequisites, and claim a slice (`dots task claim ID --owner <session> --json` or `--next`) before delegating it. Only the parent session edits tasks; workers return results. Record the PR URL with `update --pr`, close with `done` once verified, and `hold` with a reason when blocked. Task records are coordination, not evidence: confirm branch and PR state in Git/GitHub when resuming, and do not keep a lease on work nobody is doing.\n";

fn tree() -> Command {
    let mut command = Cli::command();
    command.build();
    command
}

pub(crate) fn skill() -> String {
    let tree = tree();
    let groups: Vec<_> = tree
        .get_subcommands()
        .filter(|command| command.get_name() != "skills" && !command.is_hide_set())
        .collect();
    let capabilities = groups
        .iter()
        .filter_map(|command| command.get_about())
        .map(ToString::to_string)
        .collect::<Vec<_>>()
        .join("; ");
    let description = format!(
        "Use the dots CLI for supported coding-agent workflows. Available capabilities: {capabilities}. Also use when the user names dots or asks about its available commands."
    );
    let description = serde_json::Value::String(description).to_string();
    let mut out = format!(
        "---\nname: dots\ndescription: {description}\n---\n\n<!-- Generated by dots skills render. Edit src/dots/src/command.rs and skills.rs; run mise run //src/dots:skills. -->\n\n# dots\n\n{GUIDANCE}\n## Available workflows\n\n"
    );
    for group in groups {
        workflow_index(group, "dots", &mut out);
    }
    out
}

/// Generated documentation belongs to the command tree, not a second build driver.
pub(crate) fn publish(output: &Path, check: bool) -> Result<String> {
    let artifacts = [
        ("SKILL.md", skill()),
        ("references/commands.md", reference()),
    ];
    for (name, content) in artifacts {
        let path = output.join(name);
        if check {
            let actual = std::fs::read_to_string(&path)
                .with_context(|| format!("read generated skill {}", path.display()))?;
            ensure!(
                actual == content,
                "{} is stale; regenerate the CLI skill",
                path.display()
            );
        } else {
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent)
                    .with_context(|| format!("create {}", parent.display()))?;
            }
            std::fs::write(&path, content)
                .with_context(|| format!("write generated skill {}", path.display()))?;
        }
    }
    Ok(if check {
        "CLI skill artifacts match the command tree\n"
    } else {
        "Generated CLI skill artifacts\n"
    }
    .to_owned())
}

fn workflow_index(command: &Command, parent: &str, out: &mut String) {
    let path = format!("{parent} {}", command.get_name());
    if let Some(about) = command.get_about() {
        let _ = writeln!(out, "- `{path}`: {about}. Help: `{path} --help`.");
    }
    for child in command
        .get_subcommands()
        .filter(|child| !child.is_hide_set())
    {
        workflow_index(child, &path, out);
    }
}

pub(crate) fn reference() -> String {
    let mut out = "<!-- Generated by dots skills render --reference; do not edit. -->\n\n# dots command reference\n\n".to_owned();
    render_help(&tree(), "dots", &mut out);
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

fn render_help(command: &Command, path: &str, out: &mut String) {
    let mut copy = command.clone();
    let help = copy
        .render_long_help()
        .to_string()
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    let _ = writeln!(out, "## {path}\n\n```text\n{help}\n```\n");
    for child in command
        .get_subcommands()
        .filter(|child| !child.is_hide_set())
    {
        render_help(child, &format!("{path} {}", child.get_name()), out);
    }
}

