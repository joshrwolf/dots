import assert from "node:assert/strict";
import {execFileSync} from "node:child_process";
import {existsSync, mkdirSync, mkdtempSync, readFileSync, readlinkSync, rmSync, symlinkSync, writeFileSync} from "node:fs";
import {join} from "node:path";
import {tmpdir} from "node:os";
import {test} from "node:test";
import {copyCheckout} from "./support/checkout.mjs";

test("authored snapshots preserve leaf links without following replaced directory ancestors", t => {
    const temporary = mkdtempSync(join(tmpdir(), "dots-checkout-"));
    t.after(() => rmSync(temporary, {recursive: true, force: true}));
    const source = join(temporary, "source"), external = join(temporary, "external");
    const destination = join(temporary, "copy");
    mkdirSync(join(source, "old"), {recursive: true});
    mkdirSync(external);
    const env = {...process.env, GIT_CONFIG_GLOBAL: "/dev/null", GIT_CONFIG_NOSYSTEM: "1"};
    const git = (...args) => execFileSync("git", args, {cwd: source, env, timeout: 10_000});
    git("init", "--quiet");
    writeFileSync(join(source, "old/file.txt"), "tracked old source\n");
    git("add", "old/file.txt");
    rmSync(join(source, "old"), {recursive: true});
    writeFileSync(join(external, "file.txt"), "neutral external content must not be copied\n");
    symlinkSync(external, join(source, "old"));
    writeFileSync(join(source, ".gitignore"), "/old\n");
    git("check-ignore", "--no-index", "-q", "old");
    writeFileSync(join(source, "public.txt"), "authored content\n");
    symlinkSync("public.txt", join(source, "public-link"));
    copyCheckout(source, destination);
    assert.ok(!existsSync(join(destination, "old")));
    assert.equal(readFileSync(join(destination, "public.txt"), "utf8"), "authored content\n");
    assert.equal(readlinkSync(join(destination, "public-link")), "public.txt");
    assert.ok(!existsSync(join(destination, ".git")));
});
